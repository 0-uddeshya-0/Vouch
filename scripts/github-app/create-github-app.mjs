#!/usr/bin/env node
// Runs the GitHub App Manifest flow end-to-end, locally, with zero dependencies.
//
//   1. Serves a page that auto-submits scripts/github-app/app-manifest.json to GitHub.
//   2. GitHub creates the app and redirects back to this server with a temporary code.
//   3. We exchange the code via the GitHub API and receive the App ID, private key (PEM),
//      webhook secret, and OAuth client id/secret — no manual clicking required.
//   4. Writes the PEM and a ready-to-paste .env block next to this script.
//
// Usage:
//   node scripts/github-app/create-github-app.mjs https://your-api.up.railway.app/webhooks/github
//
// Optional env:
//   GITHUB_ORG=my-org   # create under an org instead of your personal account
//   PORT=8765           # local callback port (must match app-manifest.json redirect_url)

import http from 'node:http';
import https from 'node:https';
import fs from 'node:fs';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PORT = Number(process.env.PORT || 8765);
const ORG = process.env.GITHUB_ORG || '';
const WEBHOOK_URL = process.argv[2] || process.env.WEBHOOK_URL || '';

if (!WEBHOOK_URL || /REPLACE_WITH_YOUR_API_URL/.test(WEBHOOK_URL)) {
  console.error('ERROR: pass your live webhook URL as the first argument.\n' +
    '  node scripts/github-app/create-github-app.mjs https://your-api.up.railway.app/webhooks/github');
  process.exit(1);
}

const manifest = JSON.parse(fs.readFileSync(path.join(__dirname, 'app-manifest.json'), 'utf8'));
manifest.redirect_url = `http://localhost:${PORT}/callback`;
manifest.hook_attributes = { url: WEBHOOK_URL, active: true };

const createUrl = ORG
  ? `https://github.com/organizations/${ORG}/settings/apps/new`
  : 'https://github.com/settings/apps/new';

const formPage = () => `<!doctype html><html><head><meta charset="utf-8"><title>Create Vouch GitHub App</title></head>
<body style="font-family:system-ui;margin:3rem">
<h2>Creating your Vouch GitHub App…</h2>
<p>Submitting the manifest to GitHub. Approve the app on the next screen.</p>
<form id="f" method="post" action="${createUrl}">
  <input type="hidden" name="manifest" value='${JSON.stringify(manifest).replace(/'/g, '&#39;')}'>
  <noscript><button type="submit">Continue to GitHub</button></noscript>
</form>
<script>document.getElementById('f').submit();</script>
</body></html>`;

function exchangeCode(code) {
  return new Promise((resolve, reject) => {
    const req = https.request({
      method: 'POST',
      hostname: 'api.github.com',
      path: `/app-manifests/${code}/conversions`,
      headers: {
        'Accept': 'application/vnd.github+json',
        'User-Agent': 'vouch-app-manifest-flow',
        'X-GitHub-Api-Version': '2022-11-28',
        'Content-Length': 0,
      },
    }, (res) => {
      let body = '';
      res.on('data', (c) => (body += c));
      res.on('end', () => {
        if (res.statusCode !== 201) return reject(new Error(`GitHub returned ${res.statusCode}: ${body}`));
        resolve(JSON.parse(body));
      });
    });
    req.on('error', reject);
    req.end();
  });
}

function writeOutputs(app) {
  const pemPath = path.join(__dirname, 'vouch-app-private-key.pem');
  fs.writeFileSync(pemPath, app.pem, { mode: 0o600 });

  const escapedKey = app.pem.replace(/\n/g, '\\n').trimEnd();
  const env = [
    '# --- Vouch GitHub App (generated by create-github-app.mjs) ---',
    `GITHUB_APP_ID=${app.id}`,
    `GITHUB_WEBHOOK_SECRET=${app.webhook_secret}`,
    `GITHUB_PRIVATE_KEY="${escapedKey}"`,
    '',
    '# OAuth credentials (dashboard login only):',
    `GITHUB_ID=${app.client_id}`,
    `GITHUB_SECRET=${app.client_secret}`,
    '',
  ].join('\n');
  const envPath = path.join(__dirname, '.env.github-app');
  fs.writeFileSync(envPath, env, { mode: 0o600 });
  return { pemPath, envPath };
}

const server = http.createServer(async (req, res) => {
  const url = new URL(req.url, `http://localhost:${PORT}`);
  if (url.pathname === '/' || url.pathname === '/start') {
    res.writeHead(200, { 'Content-Type': 'text/html' });
    res.end(formPage());
    return;
  }
  if (url.pathname === '/callback') {
    const code = url.searchParams.get('code');
    if (!code) { res.writeHead(400); res.end('Missing code'); return; }
    try {
      const app = await exchangeCode(code);
      const { pemPath, envPath } = writeOutputs(app);
      res.writeHead(200, { 'Content-Type': 'text/html' });
      res.end(`<body style="font-family:system-ui;margin:3rem">
        <h2>✅ App "${app.slug}" created (App ID ${app.id}).</h2>
        <p>Private key saved to <code>${pemPath}</code></p>
        <p>Env block saved to <code>${envPath}</code></p>
        <p><b>Next:</b> install the app at <a href="${app.html_url}/installations/new">${app.html_url}/installations/new</a>,
        then paste the .env values into Railway/Vercel. You can close this tab.</p>`);
      console.log('\n✅ Created GitHub App:', app.slug, '(App ID', app.id + ')');
      console.log('   Private key:', pemPath);
      console.log('   Env block:  ', envPath);
      console.log('   Install at: ', `${app.html_url}/installations/new`);
      setTimeout(() => { server.close(); process.exit(0); }, 500);
    } catch (err) {
      res.writeHead(500); res.end(String(err));
      console.error('\n❌', err.message);
      setTimeout(() => process.exit(1), 500);
    }
    return;
  }
  res.writeHead(404); res.end('Not found');
});

server.listen(PORT, () => {
  const startUrl = `http://localhost:${PORT}/`;
  console.log(`\nVouch GitHub App creator listening on ${startUrl}`);
  console.log(`Webhook URL: ${WEBHOOK_URL}`);
  console.log(ORG ? `Target org: ${ORG}` : 'Target: your personal account');
  console.log('Opening your browser… (if it does not open, visit the URL above)\n');
  const opener = process.platform === 'darwin' ? 'open' : process.platform === 'win32' ? 'start' : 'xdg-open';
  spawn(opener, [startUrl], { stdio: 'ignore', detached: true, shell: process.platform === 'win32' }).on('error', () => {});
});
